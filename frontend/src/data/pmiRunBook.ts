/**
 * Шпаргалка спикера и протокольная заготовка: по каждому пункту — требования,
 * шаги, вопросы с эталонами, автопроверки, речь и ответы на вопросы комиссии.
 */
export function runbookCheatSheet(): string {
  const lines = [
    'ПРОГОН ПМИ — ШПАРГАЛКА СПИКЕРА (приложение А, А-1…А-17)',
    'Требования и шаги — из ПМИ; речь, автопроверки и вопросы — из рабочей книги прогона.',
    `Подготовлено: ${new Date().toLocaleString('ru-RU')}`,
    '',
    `Адреса стенда: ${PMI_ADDRESSES.map((a) => `${a.label} — ${a.value}`).join(' · ')}`,
    '',
    'ПРЕДУСЛОВИЯ ПРОГОНА',
    ...PMI_PREFLIGHT.map((p) => `- [ ] ${p.text}${p.detail ? ` — ${p.detail}` : ''}${p.item ? ` (${p.item})` : ''}`),
  ];

  ANNEX_A_ITEMS.forEach((item, idx) => {
    const book = PMI_RUNBOOK[item.id];
    lines.push(
      '',
      '---',
      `ПУНКТ ${idx + 1} · ${item.id} · ${item.title} (${item.group})`,
      item.requirements.map((r) => `${r.code} (${r.title}) · ТЗ ${r.tz} · критерий: ${r.criterion}`).join('\n'),
    );
    if (book?.goal) lines.push('', `ЧТО ДОКАЗЫВАЕМ: ${book.goal}`);
    lines.push('', 'ШАГИ (таблица А.1)', ...item.steps.map((s, n) => `${n + 1}. ${s}`));
    lines.push('', `ОЖИДАЕМЫЙ РЕЗУЛЬТАТ: ${item.expected}`);
    if (book?.questions?.length) {
      lines.push('', 'ВОПРОСЫ В ЖИВОМ ЧАТЕ');
      book.questions.forEach((q) => lines.push(`- ${q.text}${q.expect ? ` → ${q.expect}` : ''}`));
    }
    if (book?.checks?.length) {
      lines.push('', 'АВТОПРОВЕРКИ ИЗ КАРТОЧКИ');
      book.checks.forEach((c) =>
        lines.push(
          `- ${c.title} — ${c.criterion}${c.slow ? ' [долго, обращается к модели]' : ''}${c.destructive ? ' [удаляет данные]' : ''}`,
        ),
      );
    }
    if (item.commands?.length) {
      lines.push('', 'КОМАНДЫ');
      item.commands.forEach((c) => lines.push(`- ${c.title}: ${c.cmd}${c.expect ? ` (ожидание: ${c.expect})` : ''}`));
    }
    if (item.artifacts?.length) lines.push('', `АРТЕФАКТЫ: ${item.artifacts.join(' · ')}`);
    if (book?.speech) lines.push('', 'РЕЧЬ ДЛЯ КОМИССИИ', book.speech);
    if (book?.tips?.length) lines.push('', 'ЗАМЕЧАНИЯ', ...book.tips.map((t) => `- ${t}`));
    if (book?.defense?.length)
      lines.push('', 'ВОПРОСЫ КОМИССИИ', ...book.defense.map((d) => `- ${d.q}\n  ${d.a}`));
  });

  return lines.join('\n');
}
