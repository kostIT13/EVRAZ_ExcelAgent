export interface RunbookQuestion {
  text: string;
  /** Что должно получиться — эталон или признак правильного поведения. */
  expect?: string;
}

export interface Runbook {
  /** Что доказываем этим пунктом — одна строка под заголовком. */
  goal?: string;
  /** Речь для комиссии — читается вслух при показе пункта. */
  speech?: string;
  /** Замечания по демонстрации (что подготовить, где подвох). */
  tips?: string[];
  /** Вероятные вопросы комиссии и ответы на них. */
  defense?: { q: string; a: string }[];
  /** Вопросы, которые задаются вживую: одним нажатием уходят в чат. */
  questions?: RunbookQuestion[];
  /** Автопроверки: реальные вызовы стенда с доказательством в строках фактов. */
  checks?: CheckDef[];
}

export interface PreflightItem {
  id: string;
  text: string;
  detail?: string;
  item?: string;
}

