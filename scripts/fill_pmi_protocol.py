def fill_paragraph(p, text: str) -> None:
    """Записывает текст в абзац, сохраняя его pPr и rPr первого заполнения."""
    for r in p.findall(q("r")):
        p.remove(r)
    proto = p.find(f"{q('pPr')}/{q('rPr')}")
    lines = text.split("\n")
    for i, line in enumerate(lines):
        run = ET.SubElement(p, q("r"))
        if proto is not None:
            run.append(ET.fromstring(ET.tostring(proto)))
        if i:
            ET.SubElement(run, q("br"))
        t = ET.SubElement(run, q("t"))
        t.set(XML_SPACE, "preserve")
        t.text = line


def cell_text(tc) -> str:
    return "".join(t.text or "" for t in tc.iter(q("t")))


def set_cell(tc, text: str) -> None:
    paragraphs = tc.findall(q("p"))
    fill_paragraph(paragraphs[0], text)
    for extra in paragraphs[1:]:
        tc.remove(extra)


